#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Standard14 {
    Courier,
    CourierBold,
    CourierBoldOblique,
    CourierOblique,
    Helvetica,
    HelveticaBold,
    HelveticaBoldOblique,
    HelveticaOblique,
    Symbol,
    TimesBold,
    TimesBoldItalic,
    TimesItalic,
    TimesRoman,
    ZapfDingbats,
}

impl Standard14 {
    #[must_use]
    pub fn from_base_font(base_font: &[u8]) -> Option<Self> {
        let name = strip_subset_prefix(strip_leading_solidus(base_font));
        ALIASES
            .iter()
            .find(|(alias, _)| *alias == name)
            .map(|(_, font)| *font)
    }

    #[must_use]
    pub fn width(self, glyph_name: &[u8]) -> Option<f64> {
        let table = self.widths();
        table
            .binary_search_by(|(name, _)| (*name).cmp(glyph_name))
            .ok()
            .map(|index| f64::from(table[index].1))
    }

    #[must_use]
    pub const fn built_in_encoding(self) -> Option<&'static [Option<&'static [u8]>; 256]> {
        match self {
            Self::Symbol => Some(&SYMBOL_ENCODING),
            Self::ZapfDingbats => Some(&ZAPF_DINGBATS_ENCODING),
            _ => None,
        }
    }

    #[must_use]
    pub fn character_for_name(self, name: &[u8]) -> Option<char> {
        if self == Self::ZapfDingbats
            && let Ok(found) =
                ZAPF_DINGBATS_UNICODE.binary_search_by(|(known, _)| (*known).cmp(name))
        {
            return char::from_u32(ZAPF_DINGBATS_UNICODE[found].1);
        }
        crate::substitute::character_for_glyph_name(name)
    }

    #[must_use]
    pub const fn is_symbolic(self) -> bool {
        matches!(self, Self::Symbol | Self::ZapfDingbats)
    }

    #[must_use]
    pub const fn name(self) -> &'static str {
        match self {
            Self::Courier => "Courier",
            Self::CourierBold => "Courier-Bold",
            Self::CourierBoldOblique => "Courier-BoldOblique",
            Self::CourierOblique => "Courier-Oblique",
            Self::Helvetica => "Helvetica",
            Self::HelveticaBold => "Helvetica-Bold",
            Self::HelveticaBoldOblique => "Helvetica-BoldOblique",
            Self::HelveticaOblique => "Helvetica-Oblique",
            Self::Symbol => "Symbol",
            Self::TimesBold => "Times-Bold",
            Self::TimesBoldItalic => "Times-BoldItalic",
            Self::TimesItalic => "Times-Italic",
            Self::TimesRoman => "Times-Roman",
            Self::ZapfDingbats => "ZapfDingbats",
        }
    }

    const fn widths(self) -> &'static [(&'static [u8], u16)] {
        match self {
            Self::Courier => COURIER,
            Self::CourierBold => COURIER_BOLD,
            Self::CourierBoldOblique => COURIER_BOLDOBLIQUE,
            Self::CourierOblique => COURIER_OBLIQUE,
            Self::Helvetica => HELVETICA,
            Self::HelveticaBold => HELVETICA_BOLD,
            Self::HelveticaBoldOblique => HELVETICA_BOLDOBLIQUE,
            Self::HelveticaOblique => HELVETICA_OBLIQUE,
            Self::Symbol => SYMBOL,
            Self::TimesBold => TIMES_BOLD,
            Self::TimesBoldItalic => TIMES_BOLDITALIC,
            Self::TimesItalic => TIMES_ITALIC,
            Self::TimesRoman => TIMES_ROMAN,
            Self::ZapfDingbats => ZAPFDINGBATS,
        }
    }
}

fn strip_leading_solidus(name: &[u8]) -> &[u8] {
    match name.split_first() {
        Some((b'/', rest)) => rest,
        _ => name,
    }
}

fn strip_subset_prefix(name: &[u8]) -> &[u8] {
    if name.len() > 7 && name[6] == b'+' && name[..6].iter().all(u8::is_ascii_uppercase) {
        return &name[7..];
    }
    name
}

