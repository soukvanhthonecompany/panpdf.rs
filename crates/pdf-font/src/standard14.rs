#[cfg(test)]
mod tests {
    use super::{Standard14, ZAPF_DINGBATS_ENCODING, ZAPF_DINGBATS_UNICODE};

    #[test]
    fn published_widths_are_what_the_table_holds() {
        for (font, glyph, expected) in [
            (Standard14::Helvetica, &b"space"[..], 278.0),
            (Standard14::Helvetica, b"A", 667.0),
            (Standard14::Helvetica, b"W", 944.0),
            (Standard14::TimesRoman, b"space", 250.0),
            (Standard14::TimesRoman, b"A", 722.0),
            (Standard14::Symbol, b"alpha", 631.0),
            (Standard14::ZapfDingbats, b"a1", 974.0),
            (Standard14::Helvetica, b"fraction", 167.0),
        ] {
            assert_eq!(font.width(glyph), Some(expected), "{}", font.name());
        }
    }

    #[test]
    fn every_dingbat_code_means_a_character() {
        let face = Standard14::ZapfDingbats;
        let name = ZAPF_DINGBATS_ENCODING[usize::from(b'4')].expect("code 4 is named");
        assert_eq!(name, b"a20");
        assert_eq!(face.character_for_name(name), Some('\u{2714}'));
        assert_eq!(face.character_for_name(b"a1"), Some('\u{2701}'));
        for name in ZAPF_DINGBATS_ENCODING.iter().flatten() {
            assert!(
                face.character_for_name(name).is_some(),
                "{}",
                String::from_utf8_lossy(name)
            );
        }
        assert!(
            ZAPF_DINGBATS_UNICODE
                .windows(2)
                .all(|pair| pair[0].0 < pair[1].0),
            "sorted, so it can be searched"
        );
        assert_eq!(Standard14::Helvetica.character_for_name(b"a20"), None);
    }

    #[test]
    fn every_courier_glyph_is_six_hundred() {
        for font in [
            Standard14::Courier,
            Standard14::CourierBold,
            Standard14::CourierOblique,
            Standard14::CourierBoldOblique,
        ] {
            let table = font.widths();
            assert_eq!(table.len(), 229, "{}", font.name());
            for (name, width) in table {
                assert_eq!(
                    *width,
                    600,
                    "{} {}",
                    font.name(),
                    String::from_utf8_lossy(name)
                );
            }
        }
    }

    #[test]
    fn every_table_is_sorted_and_reachable_by_search() {
        for font in ALL {
            let table = font.widths();
            assert!(
                table.windows(2).all(|pair| pair[0].0 < pair[1].0),
                "{} is not sorted",
                font.name()
            );
            for (name, width) in table {
                assert_eq!(font.width(name), Some(f64::from(*width)));
            }
        }
    }

    #[test]
    fn a_glyph_the_face_does_not_have_is_absent_rather_than_zero() {
        assert_eq!(Standard14::Helvetica.width(b"uni0E01"), None);
        assert_eq!(Standard14::Helvetica.width(b""), None);
    }

    #[test]
    fn a_base_font_is_recognised_through_its_subset_prefix_and_solidus() {
        assert_eq!(
            Standard14::from_base_font(b"/Helvetica"),
            Some(Standard14::Helvetica)
        );
        assert_eq!(
            Standard14::from_base_font(b"ABCDEF+Helvetica-Bold"),
            Some(Standard14::HelveticaBold)
        );
        assert_eq!(
            Standard14::from_base_font(b"/ABCDEF+TimesNewRomanPSMT"),
            Some(Standard14::TimesRoman)
        );
        assert_eq!(Standard14::from_base_font(b"ABCDE+Helvetica"), None);
        assert_eq!(Standard14::from_base_font(b"NotoSansThai"), None);
    }

    #[test]
    fn the_symbolic_encodings_reach_only_glyphs_their_face_can_measure() {
        for font in [Standard14::Symbol, Standard14::ZapfDingbats] {
            let encoding = font.built_in_encoding().expect("symbolic face");
            let named = encoding.iter().flatten().count();
            assert!(named > 180, "{} encodes only {named}", font.name());
            for name in encoding.iter().flatten() {
                assert!(
                    font.width(name).is_some(),
                    "{} encodes {} with no width",
                    font.name(),
                    String::from_utf8_lossy(name)
                );
            }
        }
    }

    #[test]
    fn only_the_two_symbolic_faces_carry_a_built_in_encoding() {
        for font in ALL {
            assert_eq!(
                font.built_in_encoding().is_some(),
                font.is_symbolic(),
                "{}",
                font.name()
            );
        }
        assert_eq!(ZAPF_DINGBATS_ENCODING.len(), 256);
    }

    const ALL: [Standard14; 14] = [
        Standard14::Courier,
        Standard14::CourierBold,
        Standard14::CourierBoldOblique,
        Standard14::CourierOblique,
        Standard14::Helvetica,
        Standard14::HelveticaBold,
        Standard14::HelveticaBoldOblique,
        Standard14::HelveticaOblique,
        Standard14::Symbol,
        Standard14::TimesBold,
        Standard14::TimesBoldItalic,
        Standard14::TimesItalic,
        Standard14::TimesRoman,
        Standard14::ZapfDingbats,
    ];
}
