#[must_use]
pub(crate) fn listed_unicode(name: &[u8]) -> Option<u32> {
    if SEQUENCE_NAMES.binary_search(&name).is_ok() {
        return None;
    }
    GLYPH_NAME_TO_UNICODE
        .binary_search_by(|(known, _)| (*known).cmp(name))
        .ok()
        .map(|found| GLYPH_NAME_TO_UNICODE[found].1)
}

#[must_use]
pub(crate) fn unicode_for_glyph_name(name: &[u8]) -> Option<u32> {
    if let Ok(found) = GLYPH_NAME_TO_UNICODE.binary_search_by(|(known, _)| (*known).cmp(name)) {
        return Some(GLYPH_NAME_TO_UNICODE[found].1);
    }
    if let Some(dot) = name.iter().position(|byte| *byte == b'.')
        && dot > 0
    {
        return unicode_for_glyph_name(&name[..dot]);
    }
    algorithmic_unicode(name)
}

fn algorithmic_unicode(name: &[u8]) -> Option<u32> {
    let (digits, expected) = if let Some(rest) = name.strip_prefix(b"uni") {
        (rest.get(..4)?, 4)
    } else {
        let rest = name.strip_prefix(b"u")?;
        match rest.len() {
            4..=6 => (rest, rest.len()),
            _ => return None,
        }
    };
    if digits.len() != expected {
        return None;
    }
    let mut value = 0_u32;
    for byte in digits {
        let digit = match byte {
            b'0'..=b'9' => u32::from(byte - b'0'),
            b'A'..=b'F' => u32::from(byte - b'A') + 10,
            _ => return None,
        };
        value = value * 16 + digit;
    }
    (!(0xD800..=0xDFFF).contains(&value) && value <= 0x0010_FFFF).then_some(value)
}

#[must_use]
pub(crate) fn mac_roman_code_for_glyph_name(name: &[u8]) -> Option<u8> {
    MAC_ROMAN_ENCODING
        .iter()
        .position(|entry| *entry == Some(name))
        .and_then(|code| u8::try_from(code).ok())
}
