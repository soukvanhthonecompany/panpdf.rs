use super::{MOST_BITS, Modulus, Number};

#[test]
fn octets_go_in_and_the_same_octets_come_out() {
    let octets = [0x01u8, 0x23, 0x45, 0x67, 0x89, 0xab, 0xcd, 0xef, 0xfe, 0xdc];
    let number = Number::from_be(&octets).expect("it fits");
    assert_eq!(number.to_be(10).expect("it fits back"), octets);
    assert_eq!(
        number.to_be(12).expect("wider is padded"),
        [
            0, 0, 0x01, 0x23, 0x45, 0x67, 0x89, 0xab, 0xcd, 0xef, 0xfe, 0xdc
        ]
    );
    assert!(
        number.to_be(4).is_none(),
        "narrower than the number is not the number"
    );
}

#[test]
fn a_power_agrees_with_another_implementation() {
    let modulus = Modulus::new(&Number::from_be(&0xd8a5_f4b3_c2e1_f00d_u64.to_be_bytes()).unwrap())
        .expect("an odd modulus");
    let base = Number::from_be(&0x1234_5678_90ab_cdef_u64.to_be_bytes()).unwrap();
    let exponent = Number::from_be(&65537u32.to_be_bytes()).unwrap();
    let answer = modulus.power(&base, &exponent).expect("the base fits");
    assert_eq!(
        u64::from_be_bytes(answer.to_be(8).unwrap().try_into().unwrap()),
        0xb801_80b8_aa7c_afba,
    );
}

#[test]
fn a_wide_modulus_agrees_too() {
    let n = KNOWN_MODULUS;
    let modulus = Modulus::new(&Number::from_be(n).expect("it fits")).expect("odd");
    let base = Number::from_be(KNOWN_BASE).expect("it fits");
    let exponent = Number::from_be(&[0x01, 0x00, 0x01]).expect("65537");
    let answer = modulus
        .power(&base, &exponent)
        .expect("the base is below it");
    assert_eq!(answer.to_be(n.len()).expect("it fits"), KNOWN_POWER);
}

#[test]
fn an_even_modulus_is_refused() {
    assert!(Modulus::new(&Number::from_be(&[0x10, 0x00]).unwrap()).is_none());
    assert!(Modulus::new(&Number::from_be(&[0x00]).unwrap()).is_none());
    assert!(Modulus::new(&Number::from_be(&[0x00, 0x03]).unwrap()).is_some());
}

#[test]
fn a_base_that_is_not_below_the_modulus_is_refused() {
    let modulus = Modulus::new(&Number::from_be(&[0x00, 0x03]).unwrap()).expect("odd");
    assert!(
        modulus
            .power(
                &Number::from_be(&[0x03]).unwrap(),
                &Number::from_be(&[0x02]).unwrap()
            )
            .is_none()
    );
    assert!(
        modulus
            .power(
                &Number::from_be(&[0x02]).unwrap(),
                &Number::from_be(&[0x02]).unwrap()
            )
            .is_some()
    );
}

#[test]
fn a_number_wider_than_any_key_is_refused() {
    assert!(Number::from_be(&vec![0xff; MOST_BITS / 8]).is_some());
    assert!(Number::from_be(&vec![0xff; MOST_BITS / 8 + 1]).is_none());
}

#[test]
fn the_smallest_exponents_come_out_right() {
    let modulus = Modulus::new(&Number::from_be(&[0x00, 0xff, 0xf1]).unwrap()).expect("odd");
    let base = Number::from_be(&[0x12, 0x34]).unwrap();
    assert_eq!(
        modulus
            .power(&base, &Number::from_be(&[0x00]).unwrap())
            .expect("it fits")
            .to_be(2),
        Some(vec![0x00, 0x01])
    );
    assert_eq!(
        modulus
            .power(&base, &Number::from_be(&[0x01]).unwrap())
            .expect("it fits")
            .to_be(2),
        Some(vec![0x12, 0x34])
    );
}

